const assert = require('node:assert/strict');
const { withLocalBrowser } = require('./lib/local-browser.cjs');

withLocalBrowser('tools-check', async browser => {
  const { navigate, fill, evaluate, waitFor, viewport, screenshot, pause } = browser;
  await navigate('/tools/season-pass');
  await waitFor('!!document.querySelector("input[name=passPrice]")');
  const values = { passPrice: '500000', ticketPrice: '50000', passTripCost: '10000', ticketTripCost: '10000', visited: '3', planned: '20' };
  for (const [key, value] of Object.entries(values)) await fill(`input[name=${key}]`, value);
  await evaluate('document.querySelector(".tool-form button[type=submit]").click()');
  await waitFor('document.querySelector(".tool-key-result strong")?.textContent === "10회"');
  assert.ok(await evaluate('document.querySelector(".tool-key-result").textContent.includes("7회")'));
  await evaluate('document.querySelector(".tool-share button").click()');
  await waitFor('!!document.querySelector(".tool-share input")');
  const shared = await evaluate('document.querySelector(".tool-share input").value');
  assert.equal(new URL(shared).search, '', 'Shared cost inputs should not be sent in HTTP query logs');
  assert.ok(new URL(shared).hash.includes('passPrice='));
  await navigate('/tools');
  await navigate(shared);
  await waitFor('document.querySelector(".tool-key-result strong")?.textContent === "10회"');
  assert.equal(await evaluate('document.querySelector("input[name=planned]").value'), '20');
  await evaluate(`location.hash=${JSON.stringify(new URLSearchParams({ ...values, passPrice: '600000' }).toString())}`);
  await waitFor('document.querySelector(".tool-key-result strong")?.textContent === "12회"');
  await evaluate(`location.hash=${JSON.stringify(new URLSearchParams(values).toString())}`);
  await waitFor('document.querySelector(".tool-key-result strong")?.textContent === "10회"');
  await screenshot('season-desktop-light');
  await evaluate('localStorage.setItem("snowthing-theme","dark"); document.documentElement.dataset.theme="dark"');
  await viewport(390, 844); await pause(100);
  assert.equal(await evaluate('document.documentElement.scrollWidth <= innerWidth'), true);
  assert.notEqual(await evaluate('getComputedStyle(document.querySelector(".community-footer nav")).display'), 'none');
  await screenshot('season-mobile-dark');
  await navigate('/tools/season-pass?passPrice=oops');
  await waitFor('!!document.querySelector("[role=alert]")');
  assert.equal(await evaluate('!!document.querySelector(".tool-key-result")'), false);

  await viewport(1440);
  await navigate('/tools/deck-size');
  await waitFor('!!document.querySelector("input[name=weight]")');
  assert.equal(await evaluate('!!document.querySelector("select[name=level]")'), false);
  assert.equal(await evaluate('!!document.querySelector("select[name=style]")'), false);
  await fill('input[name=weight]', '75'); await fill('input[name=bootMm]', '270');
  await evaluate('document.querySelector(".tool-form button").click()');
  await waitFor('document.querySelector(".tool-key-result strong")?.textContent === "152~159cm"');
  assert.ok(await evaluate('document.querySelector(".tool-key-result").textContent.includes("부츠 270mm")'));
  assert.deepEqual(await evaluate('[...document.querySelectorAll(".deck-length-guide li strong")].map(el=>el.textContent)'), ['152~153cm','154~157cm','158~159cm']);
  assert.deepEqual(await evaluate('[...document.querySelectorAll(".deck-length-guide li b")].map(el=>el.textContent)'), ['그라운드 트릭','올라운드 · 파크','라이딩']);
  await screenshot('deck-270mm');
  await fill('input[name=bootMm]', '280');
  await evaluate('document.querySelector(".tool-form button").click()');
  await waitFor('document.querySelector(".tool-key-result")?.textContent.includes("부츠 280mm")');
  assert.equal(await evaluate('!!document.querySelector(".tool-result .tool-metrics")'), false);
  await evaluate('document.querySelector(".tool-share button").click()');
  await waitFor('!!document.querySelector(".tool-share input")');
  const deckShared = await evaluate('document.querySelector(".tool-share input").value');
  assert.equal(new URL(deckShared).search, '');
  assert.ok(new URL(deckShared).hash.includes('bootMm=280'));
  assert.ok(!new URL(deckShared).hash.includes('bootUS'));
  assert.ok(!new URL(deckShared).hash.includes('level'));
  assert.ok(!new URL(deckShared).hash.includes('style'));
  await navigate('/tools'); await navigate(deckShared);
  await waitFor('document.querySelector(".tool-key-result strong")?.textContent === "152~159cm"');
  assert.equal(await evaluate('document.querySelector("input[name=bootMm]").value'), '280');
  await fill('.tool-model-fields input:first-of-type', '54');
  await fill('.tool-model-fields label:nth-child(2) input', '77');
  await waitFor('document.querySelector(".tool-explanation [role=status]")?.textContent.includes("권장 체중 안")');
  await evaluate('[...document.querySelectorAll("button")].find(b=>b.textContent==="질문 초안 확인").click()');
  await waitFor('!!document.querySelector(".tool-question-draft textarea")');
  assert.ok(await evaluate('document.querySelector(".tool-question-draft textarea").value.includes("75kg")'));
  await screenshot('deck-desktop-dark');
  await viewport(390, 844); await pause(100);
  assert.equal(await evaluate('document.documentElement.scrollWidth <= innerWidth'), true);
  await screenshot('deck-mobile-dark');
  await evaluate('document.documentElement.dataset.theme="light"');
  await screenshot('deck-mobile-light');
  await evaluate('document.querySelector(".tool-question-draft a").click()');
  await waitFor('location.pathname === "/login" && !!document.querySelector("input[type=email]")');
  assert.equal(await evaluate('new URLSearchParams(location.search).get("returnUrl")'), '/posts/create?category=QNA&draft=deck');
  if (process.env.PROFILE_CHECK_EMAIL && process.env.PROFILE_CHECK_PASSWORD) {
    await fill('input[type=email]', process.env.PROFILE_CHECK_EMAIL);
    await fill('input[type=password]', process.env.PROFILE_CHECK_PASSWORD);
    await evaluate('document.querySelector("main form button[type=submit]").click()');
    await waitFor('location.pathname === "/posts/create" && !!document.querySelector("#post-title")');
    assert.equal(await evaluate('document.querySelector("#post-title").value'), '제 조건에 맞는 데크 사이즈가 궁금합니다');
    await waitFor('[...document.querySelectorAll(".toastui-editor-contents")].some(element=>element.textContent.includes("75kg"))');
    await screenshot('question-draft-after-login');
    await evaluate(`(async()=>{const base='http://localhost:8080/api/v1'; const token=(await(await fetch(base+'/csrf',{credentials:'include'})).json()).token; await fetch(base+'/auth/logout',{method:'POST',credentials:'include',headers:{'X-XSRF-TOKEN':token}});})()`);
  }
  return { status: 'passed', checks: ['season calculation', 'shared inputs restore', 'invalid shared query rejected', 'deck range and width', 'model weight fit', 'question draft', 'anonymous login return path', ...(process.env.PROFILE_CHECK_EMAIL ? ['draft survives login'] : []), 'mobile overflow', 'light and dark screenshots'] };
}).then(result => console.log(JSON.stringify(result))).catch(error => { console.error(error.message); process.exitCode = 1; });
